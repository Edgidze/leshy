#!/usr/bin/env python3
"""Готовит присланные владельцем картинки значков к использованию в приложении.

Исходники (`docs/*.webp`) приходят как RGB чёрным по белому: без альфы, с произвольным
количеством пустого поля вокруг и с разной толщиной штриха. Ни одно из трёх свойств не годится
для `Icon()`, поэтому прогон делает три вещи.

1. **Прозрачность из яркости** (`альфа = 255 − серый`), а не отсечением по порогу: порог съел бы
   сглаживание краёв и дал бы рваный контур на маленьком размере. Но перед этим гасится «почти
   белое»: фон в исходниках не чисто белый (254, а не 255), и без гашения по всему полотну
   остаётся альфа, равная единице. Она почти невидима, зато ломает два следующих шага —
   `getbbox()` считает содержимым всё полотно, обрезка не срабатывает, и значок уезжает в масштаб
   вместе со своими исходными полями. Именно так и вышло в первой редакции: на экране секундомер
   занимал 16 dp из отведённых ему 30 и был обведён еле заметным светлым квадратом.

2. **Утолщение штриха** (`dilate_units`) для контурных значков. Замер по исходникам: штрих
   секундомера и маршрута — около 1.7 единицы сетки 24, тогда как у залитых иконок Material
   характерная толщина ближе к 2.5. Отсюда и ощущение, что они «воздушные» рядом с грибами.
   Расширение делается на исходном разрешении, до уменьшения, — так прирост попадает в
   сглаживание, а не в ступеньки. Два правила расширения выведены из ошибок второй редакции,
   см. «Порядок операций» и «Сколько расширять» ниже.

3. **Обрезка по содержимому и вписывание в поле** (`live_units` из 24). Это то, что уравнивает
   значки между собой: в исходниках содержимое секундомера занимало 685 точек по высоте против
   819 у грибов на одном и том же полотне 1092, отчего он и выглядел заметно мельче.

## Порядок операций: расширять ДО обрезки, на полотне с запасом

Расширение обязано идти по картинке, вокруг которой есть свободное поле, и рамка содержимого
обязана считаться заново уже после него. Обратный порядок (обрезали вплотную, потом расширили)
даёт ровно тот дефект, ради которого написан этот абзац: `MaxFilter` у края берёт максимум по
доступной части окна, то есть размазывает крайний пиксель наружу до границы, и круглая форма
получает прямой срез. На экране это выглядело так, будто картинка не поместилась в свою область:
у секундомера ободок был срезан снизу и с боков вместе с делениями «3 часа» и «9 часов», у
маршрута — обрезаны обе отметки мест.

## Сколько расширять: у пунктира это ограничено сверху длиной пробела

Расширение изотропно: оно наращивает штрих в стороны РОВНО настолько же, насколько удлиняет
каждый штрих пунктира вдоль линии. Пробелы между штрихами в исходнике маршрута — 31–40 точек,
поэтому расширение на 1.0 единицы (± 18 точек, то есть −36 точек на каждый пробел) съедало их
почти целиком: пунктир слипался в одну волнистую колбасу, и это читалось как размытость линии.
Отсюда потолок: маршруту 0.5 единицы, при котором пробел остаётся заметен и на 30 dp.

Обойти это утолщением нельзя — только перерисовкой исходника с более редким пунктиром.

## Форма ядра: круг, а не квадрат

`ImageFilter.MaxFilter` работает квадратным ядром, поэтому скруглениям он приделывает углы, а
диагоналям — ступеньки. В прошлой редакции это лечилось размытием по Гауссу вслед за
расширением, а размытие на радиусе маршрута (6 точек) само по себе давало ту самую мягкую,
«несфокусированную» линию. Здесь расширение идёт кругом (`dilate_disc`), и лечить нечего:
дополнительное сглаживание не нужно, край остаётся ровно таким, каким его сделает LANCZOS при
уменьшении.

Поля намеренно разные. Значок, которому в интерфейсе задан размер и который стоит сам по себе
(шапка «Записи», карточка архива), заполняет своё поле почти целиком: его видимый размер тогда
равен заданному в dp, и им можно управлять из кода. Значку в боковом меню, наоборот, нужен тот же
внутренний отступ, что у соседей-иконок Material (содержимое примерно 20 единиц из 24), иначе при
одинаковом размере он выглядит крупнее всех.

Запуск: python3 tools/prepare_icon_assets.py
"""
from PIL import Image, ImageChops

SOURCE_DIR = "docs/"
DEST_DIR = "shared/src/commonMain/composeResources/drawable/"
BBOX_FLOOR = 48  # ниже этого пиксель не участвует в рамке содержимого
WHITE_FLOOR = 16  # ниже этого альфа считается фоном; см. пункт 1 в описании модуля
CANVAS = 192  # хватает на 24dp при плотности 4x с запасом; WebP такого размера весит единицы КБ

# (исходник, имя ресурса, поле из 24, утолщение штриха в единицах сетки 24)
SPECS = [
    # Полное поле: размер задаётся из кода через Modifier.size().
    ("mushrooms", "ic_mushrooms", 23.4, 0.0),
    ("clock", "ic_stopwatch", 23.4, 0.6),
    ("route", "ic_route", 23.4, 0.5),  # потолок задан длиной пробела пунктира, см. описание модуля
    # Отдельный вариант для бокового меню: отступ как у соседних иконок Material.
    ("mushrooms", "ic_mushrooms_inset", 19.5, 0.0),
]


def _shifted(image: Image.Image, dx: int, dy: int) -> Image.Image:
    """Сдвиг с заполнением пустоты нулём. `ImageChops.offset` здесь не годится — он заворачивает
    картинку по краям, то есть при расширении у границы затягивал бы в кадр её же другой край."""
    return image.transform(
        image.size, Image.AFFINE, (1, 0, -dx, 0, 1, -dy), resample=Image.NEAREST, fillcolor=0
    )


def dilate_disc(image: Image.Image, radius: int) -> Image.Image:
    """Расширение круглым ядром: максимум по кругу указанного радиуса.

    Круг разбирается на горизонтальные отрезки — по одному на каждую строку ядра. Отрезки одной
    длины считаются один раз и переиспользуются, иначе прогон упирается в число сдвигов.
    Максимум берётся по мягкой альфе, а не по маске: край сохраняет свой профиль сглаживания и
    просто уезжает наружу на радиус."""
    horizontal_cache: dict[int, Image.Image] = {}

    def horizontal(half_width: int) -> Image.Image:
        if half_width not in horizontal_cache:
            grown = image
            for dx in range(1, half_width + 1):
                grown = ImageChops.lighter(grown, _shifted(image, dx, 0))
                grown = ImageChops.lighter(grown, _shifted(image, -dx, 0))
            horizontal_cache[half_width] = grown
        return horizontal_cache[half_width]

    result = None
    for dy in range(-radius, radius + 1):
        row = _shifted(horizontal(int((radius * radius - dy * dy) ** 0.5)), 0, dy)
        result = row if result is None else ImageChops.lighter(result, row)
    return result


def content_box(alpha: Image.Image) -> tuple[int, int, int, int]:
    """Рамка по «уверенным» пикселям. По мягкой альфе её считать нельзя: редкие слабые крапины вне
    рисунка (в исходнике грибов такие есть) переживают гашение фона, растягивают рамку, а при
    уменьшении усредняются в ноль — и значок оказывается мельче отведённого ему поля, причём у
    каждой картинки на свою величину."""
    box = alpha.point(lambda v: 255 if v >= BBOX_FLOOR else 0).getbbox()
    if box is None:
        raise SystemExit("пустая картинка")
    return box


def prepare(source_name: str, live_units: float, dilate_units: float) -> Image.Image:
    grey = Image.open(f"{SOURCE_DIR}{source_name}.webp").convert("L")
    # Гашение фона с растяжкой остатка: всё светлее WHITE_FLOOR становится полностью прозрачным,
    # а уцелевший диапазон растягивается обратно на 0..255, чтобы края не потеряли плотность.
    alpha = grey.point(lambda v: max(0, min(255, round((255 - v - WHITE_FLOOR) * 255 / (255 - WHITE_FLOOR)))))

    if dilate_units > 0:
        # Единица сетки в пикселях исходника — по длинной стороне содержимого ДО расширения:
        # после него содержимое станет больше, и единица «поедет» вслед за самим утолщением.
        box = content_box(alpha)
        unit_px = max(box[2] - box[0], box[3] - box[1]) / 24.0
        # Радиус — половина прироста толщины: расширение идёт в обе стороны от штриха.
        radius = max(1, round(dilate_units / 2 * unit_px))
        # Поле под прирост. Без него расширение упирается в границу картинки и срезает форму —
        # см. «Порядок операций» в описании модуля.
        margin = radius + 2
        padded = Image.new("L", (alpha.width + 2 * margin, alpha.height + 2 * margin), 0)
        padded.paste(alpha, (margin, margin))
        alpha = dilate_disc(padded, radius)

    alpha = alpha.crop(content_box(alpha))

    width, height = alpha.size
    scale = (CANVAS * live_units / 24.0) / max(width, height)
    resized = alpha.resize((max(1, round(width * scale)), max(1, round(height * scale))), Image.LANCZOS)

    black = Image.new("L", resized.size, 0)
    glyph = Image.merge("RGBA", (black, black, black, resized))
    out = Image.new("RGBA", (CANVAS, CANVAS), (0, 0, 0, 0))
    out.paste(glyph, ((CANVAS - resized.width) // 2, (CANVAS - resized.height) // 2))
    return out


def main() -> None:
    for source_name, dest_name, live_units, dilate_units in SPECS:
        image = prepare(source_name, live_units, dilate_units)
        image.save(f"{DEST_DIR}{dest_name}.webp", "WEBP", lossless=True, quality=100)
        ink = sum(1 for pixel in image.getdata() if pixel[3] > 8)
        print(f"{dest_name:22s} поле {live_units:>4} из 24, утолщение {dilate_units}  чернил {ink}px")


if __name__ == "__main__":
    main()
