#!/usr/bin/env python3
"""Готовит присланные владельцем картинки значков к использованию в приложении.

Исходники (`docs/*.webp`) приходят как RGB чёрным по белому: без альфы, с произвольным
количеством пустого поля вокруг и с разной толщиной штриха. Ни одно из трёх свойств не годится
для `Icon()`, поэтому прогон делает три вещи.

1. **Прозрачность из яркости** (`альфа = 255 − серый`), а не отсечением по порогу: порог съел бы
   сглаживание краёв и дал бы рваный контур на маленьком размере. Но перед этим гасится «почти
   белое»: фон в исходниках не чисто белый (254, а не 255), и без гашения по всему полотну
   остаётся альфа, равная единице. Она почти невидима, зато ломает два следующих шага —
   `getbbox()` считает содержимым всё полотно, обрезка не срабатывает, и значок уезжает в масштаб
   вместе со своими исходными полями. Именно так и вышло в первой редакции: на экране секундомер
   занимал 16 dp из отведённых ему 30 и был обведён еле заметным светлым квадратом.

2. **Утолщение штриха** (`dilate_units`) для контурных значков. Замер по исходникам: штрих
   секундомера и маршрута — около 1.7 единицы сетки 24, тогда как у залитых иконок Material
   характерная толщина ближе к 2.5. Отсюда и ощущение, что они «воздушные» рядом с грибами.
   Расширение делается на исходном разрешении, до уменьшения, — так прирост попадает в
   сглаживание, а не в ступеньки.

3. **Обрезка по содержимому и вписывание в поле** (`live_units` из 24). Это то, что уравнивает
   значки между собой: в исходниках содержимое секундомера занимало 685 точек по высоте против
   819 у грибов на одном и том же полотне 1092, отчего он и выглядел заметно мельче.

Поля намеренно разные. Значок, которому в интерфейсе задан размер и который стоит сам по себе
(шапка «Записи», карточка архива), заполняет своё поле почти целиком: его видимый размер тогда
равен заданному в dp, и им можно управлять из кода. Значку в боковом меню, наоборот, нужен тот же
внутренний отступ, что у соседей-иконок Material (содержимое примерно 20 единиц из 24), иначе при
одинаковом размере он выглядит крупнее всех.

Запуск: python3 tools/prepare_icon_assets.py
"""
from PIL import Image, ImageFilter

SOURCE_DIR = "docs/"
DEST_DIR = "shared/src/commonMain/composeResources/drawable/"
BBOX_FLOOR = 48  # ниже этого пиксель не участвует в рамке содержимого
WHITE_FLOOR = 16  # ниже этого альфа считается фоном; см. пункт 1 в описании модуля
CANVAS = 192  # хватает на 24dp при плотности 4x с запасом; WebP такого размера весит единицы КБ

# (исходник, имя ресурса, поле из 24, утолщение штриха в единицах сетки 24)
SPECS = [
    # Полное поле: размер задаётся из кода через Modifier.size().
    ("mushrooms", "ic_mushrooms", 23.4, 0.0),
    ("clock", "ic_stopwatch", 23.4, 0.6),
    ("route", "ic_route", 23.4, 1.0),
    # Отдельный вариант для бокового меню: отступ как у соседних иконок Material.
    ("mushrooms", "ic_mushrooms_inset", 19.5, 0.0),
]


def prepare(source_name: str, live_units: float, dilate_units: float) -> Image.Image:
    grey = Image.open(f"{SOURCE_DIR}{source_name}.webp").convert("L")
    # Гашение фона с растяжкой остатка: всё светлее WHITE_FLOOR становится полностью прозрачным,
    # а уцелевший диапазон растягивается обратно на 0..255, чтобы края не потеряли плотность.
    alpha = grey.point(lambda v: max(0, min(255, round((255 - v - WHITE_FLOOR) * 255 / (255 - WHITE_FLOOR)))))

    # Рамка считается по «уверенным» пикселям, а вырезается из мягкой альфы. Иначе рамку задают
    # редкие слабые крапины вне рисунка (в исходнике грибов такие есть): они переживают гашение
    # фона, растягивают рамку, а при уменьшении усредняются в ноль — и значок в итоге оказывается
    # мельче отведённого ему поля, причём у каждой картинки на свою величину.
    box = alpha.point(lambda v: 255 if v >= BBOX_FLOOR else 0).getbbox()
    if box is None:
        raise SystemExit(f"{source_name}: пустая картинка")
    alpha = alpha.crop(box)

    if dilate_units > 0:
        # Единица сетки в пикселях исходника — по длинной стороне содержимого.
        unit_px = max(alpha.size) / 24.0
        # Радиус — половина прироста толщины: расширение идёт в обе стороны от штриха.
        radius = max(1, round(dilate_units / 2 * unit_px))
        alpha = alpha.filter(ImageFilter.MaxFilter(size=radius * 2 + 1))
        # MaxFilter работает квадратным ядром и оставляет ступеньку на скруглениях —
        # лёгкое размытие возвращает краю гладкость, не съедая набранную толщину.
        alpha = alpha.filter(ImageFilter.GaussianBlur(radius=radius * 0.35))

    width, height = alpha.size
    scale = (CANVAS * live_units / 24.0) / max(width, height)
    resized = alpha.resize((max(1, round(width * scale)), max(1, round(height * scale))), Image.LANCZOS)

    black = Image.new("L", resized.size, 0)
    glyph = Image.merge("RGBA", (black, black, black, resized))
    out = Image.new("RGBA", (CANVAS, CANVAS), (0, 0, 0, 0))
    out.paste(glyph, ((CANVAS - resized.width) // 2, (CANVAS - resized.height) // 2))
    return out


def main() -> None:
    for source_name, dest_name, live_units, dilate_units in SPECS:
        image = prepare(source_name, live_units, dilate_units)
        image.save(f"{DEST_DIR}{dest_name}.webp", "WEBP", lossless=True, quality=100)
        ink = sum(1 for pixel in image.getdata() if pixel[3] > 8)
        print(f"{dest_name:22s} поле {live_units:>4} из 24, утолщение {dilate_units}  чернил {ink}px")


if __name__ == "__main__":
    main()
