package leshy.mushrooms.map.data.platform

import kotlinx.coroutines.flow.Flow

/**
 * Куда повёрнут сам телефон — компас устройства, в градусах по часовой стрелке от **истинного**
 * севера, 0..360.
 *
 * Зачем понадобился при живом GPS. Направление движения до этого считалось из двух подряд идущих
 * фиксов (`RecordViewModel.courseOverGround`) и обновлялось, только когда человек сместился хотя бы
 * на несколько метров. Стоя на месте и поворачиваясь — а именно так и ищут направление к точке —
 * он не получал нового значения вовсе: стрелка показывала курс, устаревший с прошлого шага, и
 * уводила не туда. Репорт владельца 2026-09-17.
 *
 * **Истинный, а не магнитный север — обязательное условие, а не уточнение.** Направление на цель
 * считается из координат ([leshy.mushrooms.map.domain.util.bearingDegrees]), то есть отсчитывается
 * от истинного севера; смешать его с магнитным курсом значит получить ошибку размером с магнитное
 * склонение — в Европейской части России это 8–15°, в Карелии и Мурманской области больше. Ровно
 * тот порядок, на который эта стрелка и указывает. Каждая реализация приводит курс к истинному
 * северу сама, потому что делается это на платформах по-разному (см. их комментарии).
 *
 * **Новых разрешений это не требует ни на одной платформе** — проверялось до того, как задача
 * бралась в работу, это было условие владельца. Android: датчики ориентации разрешений не имеют
 * вовсе (`HIGH_SAMPLING_RATE_SENSORS` нужен только выше 200 Гц). iOS: курс отдаёт тот же
 * `CLLocationManager` на уже выданном «При использовании», нового ключа в `Info.plist` не
 * появляется. В `CoreMotion` намеренно не лезем — вот там понадобился бы
 * `NSMotionUsageDescription`.
 *
 * Кроссплатформенной библиотеки под это нет — как и у GPS с камерой, отсюда платформенные
 * реализации (правило 6 корневого `CLAUDE.md`).
 */
interface HeadingProvider {
    /**
     * Поток курса. **Пустой поток (сразу закрывается) — компаса на устройстве нет**; вызывающий
     * обязан в этом случае остаться на своём запасном источнике, а не показывать пустую стрелку.
     *
     * Подписка держит датчик включённым, поэтому подписываться следует только пока курс реально
     * показывается — см. гейт в `RecordViewModel`.
     */
    fun heading(): Flow<Double>
}

/**
 * Минимальный поворот, начиная с которого платформа обязана прислать новое значение. Сырой компас
 * дрожит на градус-другой лёжа на столе, и без порога каждое такое дрожание доходило бы до
 * экрана — не ради экономии, а ради того, чтобы число градусов в панели навигации стояло на месте,
 * когда человек стоит на месте.
 *
 * Сглаживание поверх этого всё равно нужно (см. `HEADING_SMOOTHING_FACTOR` в `RecordViewModel`):
 * порог убирает мелкое дрожание, но делает оставшиеся изменения ступенчатыми.
 */
const val HEADING_MIN_CHANGE_DEGREES = 2.0
