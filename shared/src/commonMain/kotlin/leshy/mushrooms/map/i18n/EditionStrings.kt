package leshy.mushrooms.map.i18n

import leshy.mushrooms.map.domain.model.Edition

/**
 * Ключи, у которых текст зависит не от языка, а от **редакции**.
 *
 * Таких мало и будет мало — различие редакций держится на оформлении, а не на текстах. Но два
 * места иначе не закрыть, и оба говорят о продукте от первого лица:
 *
 * - **имя внутри интерфейса** — шапка выдвижного меню, приветственный экран, «О приложении».
 *   Это третья строка имени, отдельная и от ярлыка лаунчера («Грибные прогулки», флейворный
 *   ресурс Android), и от названия листинга в магазине;
 * - **«Данные карты»** — у мирового продукта доставку ведёт чужой сервис, у российского свой
 *   сервер. Различается не адрес, а утверждение, и подстановкой одного слова фраза не
 *   переписывается: вокруг адреса на каждом языке своя грамматика.
 *
 * ## Почему ключ, а не `if (edition == RUSSIA)` на экране
 *
 * Правило мержабельности (`docs/russia-edition/README.md`, «Правки общих экранов»): добавленный
 * файл при мердже не конфликтует, отредактированный общий — конфликтует всегда. Экран спрашивает
 * у набора, какой ключ показать, и ветвления не видит.
 *
 * ## Почему переводов два, а не сорок два
 *
 * Эти ключи показывает только российская редакция, а у неё языков ровно два
 * ([leshy.mushrooms.map.domain.model.EditionLanguages]). Сорок переводов строки, которую продукт
 * никогда не покажет, — работа без адресата. Остальные языки штатно уходят на английский фолбэк
 * ([string]), так что дыры в интерфейсе не возникает ни при каком стечении обстоятельств.
 *
 * Плата за это — исключение в проверке полноты переводов, и оно явное: [EDITION_ONLY_KEYS] знает
 * `StringsTest`. Появится у редакции третий язык (татарский, карельский) — сюда же придётся
 * добавить его переводы руками, компилятор об этом не напомнит.
 */
data class EditionStringKeys(
    /** Имя продукта внутри интерфейса. */
    val appName: StringKey,
    /** Абзац «Данные карты» в «О приложении». Содержит [TILE_HOST_PLACEHOLDER]. */
    val aboutMapDataText: StringKey,
)

fun editionStringKeysFor(edition: Edition): EditionStringKeys = when (edition) {
    Edition.WORLD -> EditionStringKeys(
        appName = StringKey.AppName,
        aboutMapDataText = StringKey.AboutMapDataText,
    )
    Edition.RUSSIA -> EditionStringKeys(
        appName = StringKey.AppNameRussia,
        aboutMapDataText = StringKey.AboutMapDataTextSelfHosted,
    )
}

/**
 * Ключи, переведённые только на `ru`/`en` — намеренно, см. KDoc [EditionStringKeys].
 *
 * Существует ради одного: `StringsTest` пропускает их в проверке полноты сорока таблиц. Список
 * явный, а не выведенный по имени ключа, чтобы забытый перевод нельзя было списать на
 * «наверное, это тоже ключ редакции».
 */
val EDITION_ONLY_KEYS: Set<StringKey> = setOf(
    StringKey.AppNameRussia,
    StringKey.AboutMapDataTextSelfHosted,
)
