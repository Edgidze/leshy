package leshy.mushrooms.map.domain.model

/**
 * Языки интерфейса, которые предлагает редакция.
 *
 * Сам [AppLanguage] при этом не трогается и остаётся общим на оба продукта — механизм из
 * сорока двух языков никуда не девается, и татарский с карельским, когда до них дойдёт, добавятся
 * туда же. Сужается только **предложение**: что показывает переключатель языка и чем ограничен
 * автоподбор по языку системы.
 *
 * Зачем сужать: сорок языков в российской сборке — лишний повод у модерации спросить, что это за
 * продукт, и лишняя работа пользователю в списке, где сорок строк на языках, которых он не знает.
 *
 * **Чего это НЕ делает, чтобы не приписывать лишнего:** переводы остаются в бинарнике все сорок
 * два. Они лежат в `shared/i18n` обычным кодом, а у Compose Resources и у общего модуля нет
 * механизма флейворов — вырезать их можно только вынеся в отдельный модуль на редакцию (тот же
 * разбор, что про второй набор иллюстраций в `docs/russia-edition/README.md`). Спящие строки
 * весят десятки килобайт и ничего не делают; спящий URL рядом с ними уже принят по той же логике.
 */
data class EditionLanguages(
    /** Порядок здесь и есть порядок в переключателе. */
    val available: List<AppLanguage>,
    /**
     * На чём открыться, если язык системы редакция не предлагает.
     *
     * У мировой это английский — единственный разумный общий знаменатель. У российской это
     * **русский**, а не английский: продукт продаётся в российской витрине и называется «карта
     * России», и телефон с татарской или башкирской локалью логичнее встретить по-русски.
     * Английский из набора при этом никуда не девается, он в переключателе вторым.
     */
    val fallback: AppLanguage,
) {
    init {
        require(available.isNotEmpty()) { "у редакции должен быть хотя бы один язык интерфейса" }
        require(fallback in available) { "фолбэк $fallback не входит в набор редакции: $available" }
        require(AppLanguage.EN in available) {
            "английский обязан быть у любой редакции: это фолбэк непереведённых ключей в i18n"
        }
    }

    /**
     * Ближайший доступный к [language]: сам [language], если редакция его предлагает, иначе
     * [fallback].
     *
     * Нужен в двух местах, и оба — не гипотетические. Язык системы может оказаться любым из
     * сорока двух (`currentDeviceLanguage`), а в `DataStore` может лежать код, выбранный в сборке
     * с другим набором — например, если пользователь переносил данные или ставил обе редакции.
     */
    fun nearest(language: AppLanguage): AppLanguage =
        if (language in available) language else fallback
}

/**
 * Российская редакция — только `ru` и `en`. Английский здесь не формальность: это фолбэк, на
 * который уходит любой ключ, не переведённый на язык пользователя, и без него в интерфейсе
 * появились бы пустые места.
 */
fun editionLanguagesFor(edition: Edition): EditionLanguages = when (edition) {
    Edition.WORLD -> EditionLanguages(available = AppLanguage.entries, fallback = AppLanguage.EN)
    Edition.RUSSIA -> EditionLanguages(
        available = listOf(AppLanguage.RU, AppLanguage.EN),
        fallback = AppLanguage.RU,
    )
}
