package leshy.mushrooms.map.domain.model

/**
 * Внешние адреса редакции — единственное место во всём `shared`, где они написаны.
 *
 * До этого адрес тайл-хоста был константой в `ui/map/MapStyle.kt`, и читали его девять файлов,
 * включая нативные снапшоттеры миниатюр и перехватчики закреплённого стиля. Переключать их нужно
 * ровно одновременно: снапшоттер, оставшийся на чужом хосте, даёт миниатюры архива на пустой
 * подложке — и узнать об этом можно только увидев архив.
 *
 * Достаётся из Koin (`initKoin(edition)` кладёт и редакцию, и её адреса), а не из composition
 * local: адреса нужны репозиториям и снапшоттерам, которые создаются задолго до первой композиции.
 *
 * **Мировой бинарник содержит строку российского хоста, по которой никогда не ходит, и наоборот.**
 * Это осознанное ослабление правила «адрес — на флейворе» из раздела 5
 * `.claude/plans/russia-edition.md`: правило написано против рекламного SDK, который собирает
 * данные и обязан физически отсутствовать (он и живёт в хостах). Спящая строка URL не отправляет
 * ничего. Взамен получается то, ради чего всё затевалось: на iOS обе редакции стоят поверх одного
 * `Shared.framework`, и сборочной константы там взять неоткуда.
 */
data class EditionEndpoints(
    /**
     * Адрес стиля карты. Из него же выводится [mapHost].
     *
     * Это загрузочный URL: живые карты берут «замороженный» стиль у `MapStyleCacheRepository`, но
     * фетчит он именно отсюда, и этот же URL уходит нативным снапшоттерам миниатюр и в
     * определение офлайн-участка (там он обязан быть сетевым: `file://` нативный загрузчик
     * MapLibre не понимает, см. `OfflineRegionRepositoryImpl`).
     */
    val mapStyleUrl: String,

    /** Адрес политики конфиденциальности — у каждого продукта в магазине свой. */
    val privacyPolicyUrl: String,
) {
    /**
     * Хост из [mapStyleUrl]. Показывается пользователю в двух местах: в баннере «карта не
     * загрузилась» и в тексте о приватности («…уходят только запросы участков карты с ...»).
     *
     * Выводится, а не задаётся: разойтись с адресом, по которому приложение реально ходит, он не
     * должен ни при какой правке. Баннер называет хост намеренно — инцидент, ради которого он
     * существует, это блокировка конкретного хоста у провайдера, и диагностируется она, только
     * если приложение говорит, какого именно.
     *
     * До 2026-09-26 текст о приватности называл у мировой редакции `openfreemap.org`, а ходило
     * приложение на `tiles.openfreemap.org`. Расхождение было настоящим — сведено решением
     * владельца; отдельное поле под «имя в прозе» при этом исчезло, чтобы новое расхождение
     * неоткуда было взяться.
     */
    val mapHost: String = mapStyleUrl.substringAfter("://").substringBefore('/')
}

/**
 * Мировой набор — ровно те адреса, что стояли в коде до сведения их в одно место.
 * Российский — контракт из `docs/russia-edition/README.md`, раздел «Контракт „приложение ↔
 * сервер"»; после публикации он не меняется.
 */
fun editionEndpointsFor(edition: Edition): EditionEndpoints = when (edition) {
    Edition.WORLD -> EditionEndpoints(
        // Стиль «liberty» OpenFreeMap: бесплатный, без ключа и без квоты — в отличие от растровых
        // тайлов tile.openstreetmap.org, которые community-сервис только для лёгкого
        // использования и вдобавок мылят на HiDPI (варианта @2x у них нет).
        mapStyleUrl = "https://tiles.openfreemap.org/styles/liberty",
        privacyPolicyUrl = "https://leshy-mapper.github.io/mushrooms-map/privacy.html",
    )
    Edition.RUSSIA -> EditionEndpoints(
        mapStyleUrl = "https://tiles.gribnye-progulki.ru/styles/liberty",
        privacyPolicyUrl = "https://gribnye-progulki.ru/privacy",
    )
}
