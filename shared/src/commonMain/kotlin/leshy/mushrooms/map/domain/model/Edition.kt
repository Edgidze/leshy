package leshy.mushrooms.map.domain.model

/**
 * Редакция продукта. Двух редакций два **разных приложения** в магазинах, с разными
 * `applicationId`/bundle id, а не один продукт с переключателем внутри: см.
 * `docs/russia-edition/README.md`, раздел «Почему продуктов всё-таки два».
 *
 * **Значение приходит от хоста ровно один раз, при старте** — `initKoin(edition)` из
 * `LeshyApplication.onCreate` на Android и из `MainViewController(edition)` на iOS, — и дальше
 * никем не меняется. Внутри `shared` его неоткуда вычислить, и это не небрежность, а
 * требование к переносимости на iOS: там обе редакции стоят поверх ОДНОГО И ТОГО ЖЕ
 * `Shared.framework` (второй таргет отличается только bundle id, `Info.plist` и каталогом
 * ассетов), отдельного фреймворка на редакцию не существует, и сборочной константы вроде
 * `BuildConfig` внутри `shared` там просто негде взять. Способ через `BuildConfig` работал бы
 * на Android и не переносился на iOS вообще.
 *
 * На Android редакцию выбирает измерение флейворов `edition` (`androidApp/build.gradle.kts`),
 * а конкретное значение приходит из флейворного source set — `androidApp/src/world/kotlin` и
 * `androidApp/src/russia/kotlin`.
 */
enum class Edition(
    /**
     * Файл с наборами видов этой редакции внутри `composeResources` — или `null`, если у редакции
     * наборов нет и подборки собираются по странам, как было всегда.
     *
     * Наборы заменяют подборку **одной** страны, названной в самом файле: у российской редакции
     * вместо одной «России» на 171 вид идут базовый набор и дополнения под тип леса
     * (`data/catalog/SpeciesSetsSource.kt`). Путь живёт здесь, а не внутри источника, ровно по той
     * же причине, по какой здесь живут адреса и языки: всё, чем редакции различаются, обязано
     * перечисляться в одном месте, а не находиться поиском по коду.
     */
    val speciesSetsPath: String?,
    /**
     * Начало имени файла, которым редакция называет архив экспорта дневника
     * («leshy-export-20260818-1652.zip»).
     *
     * Мелочь, которую видно: имя подставляется в поле «Имя архива» и остаётся в файловой системе
     * пользователя надолго. «leshy» в российском продукте — тот же остаток мировой редакции, что
     * и «Леший» в шапке (задача 14 `docs/russia-edition/track-app.md`), только заметный не в
     * интерфейсе, а в папке «Загрузки».
     *
     * На разбор архива имя не влияет: импорт смотрит в содержимое, а не в название файла.
     */
    val exportArchivePrefix: String,
) {
    /** «Леший: карта грибов», `leshy.mushrooms.map`. Мировой продукт, OpenFreeMap, 42 языка. */
    WORLD(speciesSetsPath = null, exportArchivePrefix = "leshy-export"),

    /** «Грибные прогулки: карта России», `ru.gribnyeprogulki.map`. Свой тайл-хост, ru+en. */
    RUSSIA(speciesSetsPath = "files/catalog/sets-ru.json", exportArchivePrefix = "gribnye-export"),
}
