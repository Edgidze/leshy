package leshy.mushrooms.map.domain.model

/**
 * Пользовательский выбор оформления. В отличие от соседнего [AppLanguage], своего
 * `displayName` не несёт: названия языков не переводятся (каждый показывается на самом себе),
 * а «Светлая»/«Тёмная»/«Системная» переводятся — значит, идут через `StringKey`, как варианты
 * `DataMode` на экране «Экспорт/Импорт».
 *
 * **Порядок вариантов здесь — это порядок строк в «Настройках»** (`SettingsScreen` строит список
 * прямо по `entries`), и «Системная» стоит между светлой и тёмной намеренно: три варианта читаются
 * как шкала, а не как перечисление, и системная тема — не третий вариант в конце, а нейтральная
 * середина между двумя крайностями. Довод не изменился, когда ряд сегментированных кнопок стал
 * вертикальным списком радиокнопок: сверху вниз шкала читается ровно так же.
 *
 * Переставлять порядок безопасно: в DataStore значение хранится ИМЕНЕМ (`mode.name`,
 * `SettingsRepositoryImpl`), не порядковым номером, — у уже установленных копий выбор не
 * съедет. `SYSTEM` заодно остаётся значением по умолчанию (там же, `?: ThemeMode.SYSTEM`).
 */
enum class ThemeMode { LIGHT, SYSTEM, DARK }
