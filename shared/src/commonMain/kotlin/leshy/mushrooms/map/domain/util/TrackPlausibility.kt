package leshy.mushrooms.map.domain.util

import leshy.mushrooms.map.domain.model.GeoPoint

/**
 * Физически возможная скорость перемещения между двумя фиксами, м/с. 60 м/с — это 216 км/ч: доехать
 * машиной между двумя местами можно, телепортироваться нельзя. Всё, что выше, — скачок приёмника, а
 * не пройденный путь.
 *
 * Порог сознательно взят с большим запасом над любым реальным способом добраться до леса или до
 * воды. Задача правила — поймать НЕВОЗМОЖНОЕ, а не отличить пешехода от автомобиля: попытка
 * угадать способ передвижения выбрасывала бы настоящие данные, а это куда хуже.
 */
const val MAX_PLAUSIBLE_SPEED_MPS = 60.0

/**
 * После какого перерыва между фиксами скачок перестаёт быть скачком, секунды. Приложение могло не
 * получать геопозицию полчаса — телефон в кармане, нет неба над головой, служба выключена, — и за
 * это время человек действительно уехал за сто километров. Новая координата при этом верна, но
 * пути между двумя точками мы не видели, и приписывать его к пройденному нельзя.
 */
const val TRACK_STALE_GAP_SECONDS = 300L

/**
 * Что делать с очередным фиксом, пришедшим после [previous].
 *
 * **Зачем это вообще.** Приёмник регулярно отдаёт фикс из другого места: «холодный» первый фикс,
 * переход с вышек на спутники, выход из-под моста, возврат приложения из фона. Без проверки такой
 * фикс честно ложится в сумму пройденного — и прогулка получает лишние сотни километров.
 * Воспроизведено на эмуляторе 2026-09-28: 633 км за две секунды. После такого числу в шапке
 * перестают верить целиком, а починить запись задним числом нечем — расстояние хранится
 * накопленным.
 *
 * Правило общее для обоих продуктов репозитория (прогулка за грибами, рыбалка) и живёт в `:shared`
 * именно поэтому: разъехаться двум копиям здесь нельзя.
 */
sealed interface TrackStep {
    /** Точка продолжает трек: записать её и прибавить [meters] к пройденному. */
    data class Continues(val meters: Double) : TrackStep

    /**
     * Скачок приёмника: не записывать вовсе и НЕ двигать «последнюю точку» — следующий фикс должен
     * мериться от последней достоверной, а не от выброшенной. Записать её значило бы прочертить
     * через весь экран линию, которой не было.
     */
    data object ReceiverJump : TrackStep

    /** Вернулись после долгого перерыва: точку записать, расстояние не прибавлять. */
    data object ResumedAfterGap : TrackStep
}

fun trackStep(previous: GeoPoint, next: GeoPoint): TrackStep {
    val meters = haversineMeters(previous.lat, previous.lon, next.lat, next.lon)
    // Единица в знаменателе, а не ноль: два фикса с одной меткой времени дают деление на ноль, а
    // отрицательную разницу (часы устройства перевели назад) считать скоростью тем более нельзя.
    val elapsedSeconds = ((next.timestamp - previous.timestamp) / 1000).coerceAtLeast(1L)
    return when {
        meters / elapsedSeconds <= MAX_PLAUSIBLE_SPEED_MPS -> TrackStep.Continues(meters)
        elapsedSeconds < TRACK_STALE_GAP_SECONDS -> TrackStep.ReceiverJump
        else -> TrackStep.ResumedAfterGap
    }
}
