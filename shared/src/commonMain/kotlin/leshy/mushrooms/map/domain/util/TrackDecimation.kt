package leshy.mushrooms.map.domain.util

/**
 * Каждая [stride]-я точка трека, но **первая и последняя — всегда**.
 *
 * Нужно для фоновых линий прошлых маршрутов на экране «Запись»: точки трека пишутся примерно раз
 * в секунду (на iOS — без минимальной дистанции вовсе), то есть с шагом порядка метра, и на
 * масштабе приглушённой линии в 2dp разница между «каждой» и «каждой четвёртой» не видна, зато
 * данных вчетверо меньше — и в памяти, и в GeoJSON, который уезжает в MapLibre.
 *
 * Гарантии первой и последней точки не косметические, а обязательные, и обе выведены из
 * воспроизведённых ошибок предыдущей (SQL-ной, `sequence % stride = 0`) версии прореживания:
 * - **последняя точка**: без неё линия обрывается, не доходя до конца маршрута, — в SQL-версии
 *   хвост выживал, только если номер последней точки случайно оказывался кратен шагу;
 * - **не меньше двух точек**, если их было не меньше двух: `LiveTrackMap`/`AggregatedFindsMap`
 *   рисуют `LineLayer` только при `points.size >= 2`, поэтому у короткой прогулки маршрут
 *   пропадал целиком. Воспроизведено на прогулке из 4 точек при шаге 4: выживала одна.
 */
fun <T> decimateTrack(points: List<T>, stride: Int): List<T> {
    require(stride >= 1) { "stride must be >= 1, was $stride" }
    if (stride == 1 || points.size <= 2) return points
    val lastIndex = points.lastIndex
    val result = ArrayList<T>(lastIndex / stride + 2)
    var index = 0
    while (index <= lastIndex) {
        result.add(points[index])
        index += stride
    }
    // Цикл заканчивается на последнем кратном шагу индексе; если это не сам конец трека —
    // дописать конец явно.
    if (lastIndex % stride != 0) result.add(points[lastIndex])
    return result
}
