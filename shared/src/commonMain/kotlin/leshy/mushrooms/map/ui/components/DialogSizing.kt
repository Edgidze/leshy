package leshy.mushrooms.map.ui.components

import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.layout.widthIn
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp

/**
 * Потолок ширины диалога. Число не выдумано: ровно его ставит себе сам Material 3 —
 * `BasicAlertDialog` оборачивает содержимое в `sizeIn(minWidth = 280.dp, maxWidth = 560.dp)`
 * (`AlertDialog.kt`, `DialogMinWidth`/`DialogMaxWidth`). Смысл потолка не в эстетике: диалог — это
 * короткий вопрос, а не страница, и на строке шире ~560dp глаз перестаёт попадать в начало
 * следующей строки, а кнопки «Отмена»/«Готово» разъезжаются по разным краям вместо того, чтобы
 * стоять группой.
 */
private val DIALOG_MAX_WIDTH = 560.dp

/**
 * Доля ширины экрана, которую диалог занимает, пока не упёрся в потолок. Именно доля, а не число:
 * на телефоне поля по краям должны быть заметны глазу, а не равны фиксированным N точкам, которые
 * на узком экране съедят половину содержимого, а на широком превратятся в ниточку.
 *
 * Было два числа — 0.9 у диалогов на `AlertDialog` и 0.92 у собранных вручную на `Surface`
 * (плюс 0.95 у одного). Разница ни из чего не следовала и ничего не значила; сведены в одно.
 */
private const val DIALOG_WIDTH_FRACTION = 0.92f

/**
 * Ширина любого диалога приложения: доля экрана на телефоне, [DIALOG_MAX_WIDTH] на широком экране.
 *
 * Заведено потому, что все диалоги проекта идут с `usePlatformDefaultWidth = false` — платформенная
 * ширина отключена сознательно, чтобы задавать её самим, — и вместе с ней отключался потолок:
 * доля экрана на планшете давала диалог за 1000dp, полосу во весь экран с тремя элементами
 * управления посередине. У девяти диалогов на `AlertDialog` при этом отключался ещё и СОБСТВЕННЫЙ
 * потолок Material 3, см. ниже.
 *
 * **Порядок вызовов в цепочке обязателен именно такой, обратный не работает.** `fillMaxWidth(доля)`
 * прибивает ребёнку `minWidth = maxWidth`, то есть задаёт точную ширину, а не предел; идущий следом
 * `widthIn(max = ...)` обязан уважать пришедший `minWidth` и потолок применить уже не может. Ровно
 * на этом и ломался встроенный потолок `AlertDialog`: модификатор вызывающего стоит в его цепочке
 * ПЕРЕД `sizeIn(...)`, поэтому наш `fillMaxWidth(0.9f)` отменял материаловские 560dp. Здесь потолок
 * идёт первым и ограничивает то, от чего доля потом считается.
 *
 * Высоты не касается: у диалогов со списком (`MapFilterDialog`, `WalksPickerDialog`,
 * `AddPlaceDialog`, `PlaceViewDialog`) к этому модификатору дописан свой `fillMaxHeight(...)`.
 */
fun Modifier.dialogWidth(): Modifier = widthIn(max = DIALOG_MAX_WIDTH).fillMaxWidth(DIALOG_WIDTH_FRACTION)
