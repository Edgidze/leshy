package klev.fishing.map.domain.model

/**
 * Пойманная (или упущенная) рыба — одна запись на один экземпляр.
 *
 * **Это и есть то место, где рыбалка перестаёт быть грибами.** У гриба находка — счётчик: нажал
 * «+», в корзине стало на один больше. У рыбы у каждого экземпляра свой вес, своя приманка и свой
 * исход, и «плюс один» не сохраняет ничего из того, ради чего дневник ведут. Поэтому таблица своя,
 * а не грибная с добавленными колонками — см. `.claude/plans/product-family.md`, раздел 2.
 *
 * Упущенная рыба — [CatchOutcome.LOST] — полноправная запись, а не отсутствие записи. Она стоит на
 * карте, попадает в статистику приманок и отвечает на вопрос «на что брало», даже когда не взяли:
 * поклёвка была. У грибов аналога нет в принципе.
 */
data class Catch(
    val id: Long,
    val tripId: Long,
    val speciesId: Long,
    val lat: Double,
    val lon: Double,
    val timestamp: Long,
    /** Граммы. `null` — не взвешивали; это нормальный и частый случай, не ошибка ввода. */
    val weightGrams: Int?,
    /** Миллиметры. `null` — не мерили. */
    val lengthMm: Int?,
    /**
     * Глубина в месте поимки, сантиметры. `null` — не знали или не смотрели.
     *
     * Сантиметры, а не метры: с лодки и со льда глубину читают с эхолота или глубиномера с
     * точностью до десятков сантиметров («три сорок»), и целые метры такую запись огрубляют.
     */
    val depthCm: Int?,
    /** Приманка или наживка словами. Справочника нет сознательно: у каждого свой язык («мотыль»,
     *  «вертушка №2», «кукуруза»), и закрытый список его только обрежет. Подсказки собираются из
     *  того, что пользователь уже вводил. */
    val bait: String?,
    val outcome: CatchOutcome,
    /** Заполняется только при [CatchOutcome.LOST]. */
    val lostReason: LostReason?,
    val photoPath: String?,
    val note: String?,
)

enum class CatchOutcome {
    /** Взята. */
    KEPT,

    /** Отпущена. */
    RELEASED,

    /** Сошла, ушла, не добрали. */
    LOST,
}

/**
 * Почему упустили. Закрытый список — в отличие от приманки: причин схода конечное число, они
 * повторяются у всех, и по ним осмысленно считать статистику («половина сходов — на вертушке
 * без поводка»). Свободный текст для остального лежит в [Catch.note].
 */
enum class LostReason {
    /** Сошла при вываживании. */
    CAME_OFF,

    /** Обрыв лески или поводка. */
    LINE_BROKE,

    /** Разогнулся или сломался крючок. */
    HOOK_FAILED,

    /** Сломалась снасть. */
    TACKLE_BROKE,

    /** Ушла в коряги, камни, траву. */
    SNAGGED,

    /** Упустили у берега или у борта. */
    LOST_AT_LANDING,

    /** Другое — подробности в заметке. */
    OTHER,
}

/** Верхний предел веса: 200 кг отсекает опечатку на порядок, оставляя любую реальную рыбу. */
const val MAX_CATCH_WEIGHT_GRAMS = 200_000

/** Верхний предел длины: 3 метра. */
const val MAX_CATCH_LENGTH_MM = 3_000

/**
 * Верхний предел глубины: 500 метров. Отсекает опечатку на порядок, оставляя любую реальную
 * рыбалку — глубоководный троллинг на больших озёрах и морская ловля с лодки в этот предел
 * укладываются с запасом.
 */
const val MAX_CATCH_DEPTH_CM = 50_000
