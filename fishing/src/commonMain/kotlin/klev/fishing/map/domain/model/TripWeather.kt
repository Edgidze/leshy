package klev.fishing.map.domain.model

/**
 * Условия выезда — то, ради чего рыбацкий дневник вообще открывают («что клевало при падающем
 * давлении»).
 *
 * **Заполняет человек, а не сеть, и это решение владельца, а не ограничение реализации.** База
 * погоды знает погоду в узле сетки за час, а рыбак ловил в конкретной точке в конкретные минуты;
 * над водой, в затишке под берегом или на ветродуе показания расходятся с моделью заметно.
 * Поэтому источник истины здесь — память рыбака, а внешний API умеет ровно одно: ПОДСКАЗАТЬ, что
 * по мнению интернета было в этом месте в это время, и подставить это в поля, которые человек
 * потом правит. [provenance] запоминает, чем кончился этот разговор.
 *
 * Практическое следствие: приложение полностью работоспособно без сети и без разрешений, а отказ
 * погодного сервиса не ломает ничего, кроме кнопки «подсказать».
 *
 * Все поля необязательны: половину рыбак не вспомнит, и это не повод не сохранить остальное.
 */
data class TripWeather(
    val airTempC: Double?,
    val waterTempC: Double?,
    /** Давление в гектопаскалях (оно же миллибары). Показывается в тех единицах, что выбраны в
     *  настройках; в базе всегда гПа, чтобы не пересчитывать при смене настройки. */
    val pressureHpa: Double?,
    /** Тенденция давления за сутки — то, что рыболовы обсуждают чаще абсолютного значения. */
    val pressureTrend: PressureTrend?,
    val windSpeedMps: Double?,
    val windDirection: WindDirection?,
    val cloudiness: Cloudiness?,
    val precipitation: Precipitation?,
    val provenance: WeatherProvenance,
)

enum class PressureTrend {
    RISING,
    STEADY,
    FALLING,
}

enum class WindDirection {
    N, NE, E, SE, S, SW, W, NW,
}

enum class Cloudiness {
    CLEAR,
    PARTLY,
    OVERCAST,
}

enum class Precipitation {
    NONE,
    DRIZZLE,
    RAIN,
    SHOWER,
    SNOW,
}

/**
 * Откуда взялись значения. Нужно не для отчётности, а чтобы потом не спорить с собственными
 * данными: цифра, которую подставил сервис и никто не тронул, — это мнение модели о точке в сетке,
 * а не наблюдение.
 */
enum class WeatherProvenance {
    /** Всё ввёл человек, подсказкой не пользовались. */
    USER,

    /** Подставлено подсказкой и принято как есть. */
    SUGGESTED,

    /** Подставлено подсказкой и поправлено человеком. */
    SUGGESTED_EDITED,
}
