package klev.fishing.map.domain.model

/**
 * Одна рыбалка — то, чем для грибного «Лешего» является прогулка. Отличия от неё две штуки, и обе
 * не косметические: у рыбалки есть СПОСОБ (с берега, с лодки, со льда — от него зависит и трек, и
 * то, как читается карта) и есть ПОГОДА, которую вносит сам рыбак по окончании.
 *
 * Погода живёт здесь, а не у каждого улова: она свойство выезда, а не рыбы. За время рыбалки она,
 * конечно, меняется — но человек, который вспоминает вечером «было пасмурно, давление падало»,
 * описывает выезд целиком, и требовать от него погоду на каждую поклёвку значит не получить её
 * вовсе.
 */
data class Trip(
    val id: Long,
    val startedAt: Long,
    val finishedAt: Long?,
    /** Пользовательское имя. Пусто — экран покажет дату и водоём. */
    val title: String?,
    /** Снимок маршрута для списка архива: имя файла в хранилище снимков приложения. */
    val thumbnailPath: String?,
    val method: FishingMethod,
    /** Пройденное за рыбалку, метры. Хранится, а не считается по треку при показе: трек на
     *  отрисовку прореживается, и сумма по прореженному тем меньше настоящей, чем сильнее
     *  прореживание. */
    val distanceMeters: Double,
    /** Название водоёма словами — вводит пользователь, справочника водоёмов в приложении нет. */
    val waterBody: String?,
    val weather: TripWeather?,
) {
    val isActive: Boolean get() = finishedAt == null

    val durationMillis: Long? get() = finishedAt?.let { it - startedAt }
}

enum class FishingMethod {
    SHORE,
    BOAT,
    ICE,
}
